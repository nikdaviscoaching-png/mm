CREATE TABLE IF NOT EXISTS items(id TEXT PRIMARY KEY,data TEXT NOT NULL,version INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS config(key TEXT PRIMARY KEY,value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS jobs(id TEXT PRIMARY KEY,data TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'waiting_worker',claimed_by TEXT,lease_until REAL,created REAL NOT NULL);
CREATE INDEX IF NOT EXISTS jobs_claim ON jobs(status,lease_until,created);
CREATE TABLE IF NOT EXISTS captures(id TEXT PRIMARY KEY,data TEXT NOT NULL,updated REAL NOT NULL);
CREATE TABLE IF NOT EXISTS events(id TEXT PRIMARY KEY,created TEXT,kind TEXT,data TEXT);
CREATE TABLE IF NOT EXISTS attempts(id TEXT PRIMARY KEY,created TEXT,data TEXT);
CREATE TABLE IF NOT EXISTS orders(id TEXT PRIMARY KEY,data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS holds(item_id TEXT PRIMARY KEY REFERENCES items(id),order_id TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS media(key TEXT PRIMARY KEY,data TEXT NOT NULL,created REAL NOT NULL);
CREATE TABLE IF NOT EXISTS uploads(id TEXT PRIMARY KEY,data TEXT NOT NULL,created REAL NOT NULL);
CREATE TABLE IF NOT EXISTS webhook_events(id TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS action_keys(key TEXT PRIMARY KEY,result TEXT NOT NULL,created REAL NOT NULL);
CREATE TABLE IF NOT EXISTS market_links(provider TEXT NOT NULL,item_id TEXT NOT NULL,listing_id TEXT NOT NULL,data TEXT NOT NULL,PRIMARY KEY(provider,item_id));
CREATE TABLE IF NOT EXISTS market_jobs(id TEXT PRIMARY KEY,data TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'queued',lease_until REAL,claimed_by TEXT);
CREATE TABLE IF NOT EXISTS market_sales(id TEXT PRIMARY KEY,data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS market_oauth(state TEXT PRIMARY KEY,data TEXT NOT NULL,expires REAL NOT NULL);
